    async def _run_llm_evaluations(self, 
                                 translation_pairs: List[Dict[str, Any]], 
                                 enable_ensemble: bool) -> List[Dict[str, Any]]:
        """Run LLM evaluations for all translation pairs."""
        
        evaluation_results = []
        
        # Process in batches to avoid API rate limits
        batch_size = 5
        for i in range(0, len(translation_pairs), batch_size):
            batch = translation_pairs[i:i + batch_size]
            
            # Process batch
            batch_tasks = []
            for pair in batch:
                if enable_ensemble:
                    # Ensemble evaluation for both systems
                    og_rag_task = self.llm_evaluator.ensemble_evaluation(
                        pair['kikuyu_original'],
                        pair['og_rag_translation'],
                        'og_rag',
                        f"{pair['proverb_id']}_og_rag"
                    )
                    raw_llm_task = self.llm_evaluator.ensemble_evaluation(
                        pair['kikuyu_original'],
                        pair['raw_llm_translation'],
                        'raw_llm',
                        f"{pair['proverb_id']}_raw_llm"
                    )
                else:
                    # Single model evaluation
                    og_rag_task = self.llm_evaluator.evaluate_single_translation(
                        pair['kikuyu_original'],
                        pair['og_rag_translation'],
                        'og_rag',
                        f"{pair['proverb_id']}_og_rag"
                    )
                    raw_llm_task = self.llm_evaluator.evaluate_single_translation(
                        pair['kikuyu_original'],
                        pair['raw_llm_translation'],
                        'raw_llm',
                        f"{pair['proverb_id']}_raw_llm"
                    )
                    
                batch_tasks.extend([og_rag_task, raw_llm_task])
                
            # Execute batch
            try:
                batch_results = await asyncio.gather(*batch_tasks, return_exceptions=True)
                
                # Process batch results
                for j, pair in enumerate(batch):
                    og_rag_idx = j * 2
                    raw_llm_idx = j * 2 + 1
                    
                    og_rag_result = batch_results[og_rag_idx] if og_rag_idx < len(batch_results) else None
                    raw_llm_result = batch_results[raw_llm_idx] if raw_llm_idx < len(batch_results) else None
                    
                    if not isinstance(og_rag_result, Exception) and not isinstance(raw_llm_result, Exception):
                        evaluation_results.append({
                            'proverb_data': pair,
                            'og_rag_evaluation': og_rag_result,
                            'raw_llm_evaluation': raw_llm_result,
                            'evaluation_type': 'ensemble' if enable_ensemble else 'single'
                        })
                    else:
                        logger.warning(f"Evaluation failed for {pair['proverb_id']}")
                        
                # Rate limiting pause
                await asyncio.sleep(1)
                
            except Exception as e:
                logger.error(f"Batch evaluation failed: {e}")
                continue
                
        logger.info(f"Completed {len(evaluation_results)} evaluations")
        return evaluation_results
        
    def _perform_statistical_analysis(self, evaluation_results: List[Dict[str, Any]]) -> Dict[str, Any]:
        """Perform statistical analysis on evaluation results."""
        
        # Extract scores for analysis
        og_rag_scores = []
        raw_llm_scores = []
        
        cultural_og_rag = []
        cultural_raw_llm = []
        accuracy_og_rag = []
        accuracy_raw_llm = []
        business_og_rag = []
        business_raw_llm = []
        fluency_og_rag = []
        fluency_raw_llm = []
        
        for result in evaluation_results:
            # Handle ensemble vs single evaluation results
            og_rag_eval = result['og_rag_evaluation']
            raw_llm_eval = result['raw_llm_evaluation']
            
            if isinstance(og_rag_eval, dict) and 'ensemble_summary' in og_rag_eval:
                # Ensemble evaluation
                og_rag_score = og_rag_eval['ensemble_summary']['mean_scores']['weighted_score']
                cultural_og = og_rag_eval['ensemble_summary']['mean_scores']['cultural_faithfulness']
                accuracy_og = og_rag_eval['ensemble_summary']['mean_scores']['translation_accuracy']
                business_og = og_rag_eval['ensemble_summary']['mean_scores']['business_relevance']
                fluency_og = og_rag_eval['ensemble_summary']['mean_scores']['overall_fluency']
            else:
                # Single evaluation
                og_rag_score = og_rag_eval.weighted_score
                cultural_og = og_rag_eval.evaluation_criteria.cultural_faithfulness
                accuracy_og = og_rag_eval.evaluation_criteria.translation_accuracy
                business_og = og_rag_eval.evaluation_criteria.business_relevance
                fluency_og = og_rag_eval.evaluation_criteria.overall_fluency
                
            if isinstance(raw_llm_eval, dict) and 'ensemble_summary' in raw_llm_eval:
                # Ensemble evaluation
                raw_llm_score = raw_llm_eval['ensemble_summary']['mean_scores']['weighted_score']
                cultural_raw = raw_llm_eval['ensemble_summary']['mean_scores']['cultural_faithfulness']
                accuracy_raw = raw_llm_eval['ensemble_summary']['mean_scores']['translation_accuracy']
                business_raw = raw_llm_eval['ensemble_summary']['mean_scores']['business_relevance']
                fluency_raw = raw_llm_eval['ensemble_summary']['mean_scores']['overall_fluency']
            else:
                # Single evaluation
                raw_llm_score = raw_llm_eval.weighted_score
                cultural_raw = raw_llm_eval.evaluation_criteria.cultural_faithfulness
                accuracy_raw = raw_llm_eval.evaluation_criteria.translation_accuracy
                business_raw = raw_llm_eval.evaluation_criteria.business_relevance
                fluency_raw = raw_llm_eval.evaluation_criteria.overall_fluency
                
            # Collect scores
            og_rag_scores.append(og_rag_score)
            raw_llm_scores.append(raw_llm_score)
            
            cultural_og_rag.append(cultural_og)
            cultural_raw_llm.append(cultural_raw)
            accuracy_og_rag.append(accuracy_og)
            accuracy_raw_llm.append(accuracy_raw)
            business_og_rag.append(business_og)
            business_raw_llm.append(business_raw)
            fluency_og_rag.append(fluency_og)
            fluency_raw_llm.append(fluency_raw)
            
        # Perform statistical tests
        statistical_results = {
            'sample_size': len(evaluation_results),
            'overall_scores': {
                'og_rag': {
                    'mean': np.mean(og_rag_scores),
                    'std': np.std(og_rag_scores),
                    'median': np.median(og_rag_scores),
                    'min': np.min(og_rag_scores),
                    'max': np.max(og_rag_scores)
                },
                'raw_llm': {
                    'mean': np.mean(raw_llm_scores),
                    'std': np.std(raw_llm_scores),
                    'median': np.median(raw_llm_scores),
                    'min': np.min(raw_llm_scores),
                    'max': np.max(raw_llm_scores)
                }
            },
            'dimension_analysis': {
                'cultural_faithfulness': {
                    'og_rag_mean': np.mean(cultural_og_rag),
                    'raw_llm_mean': np.mean(cultural_raw_llm),
                    'difference': np.mean(cultural_og_rag) - np.mean(cultural_raw_llm)
                },
                'translation_accuracy': {
                    'og_rag_mean': np.mean(accuracy_og_rag),
                    'raw_llm_mean': np.mean(accuracy_raw_llm),
                    'difference': np.mean(accuracy_og_rag) - np.mean(accuracy_raw_llm)
                },
                'business_relevance': {
                    'og_rag_mean': np.mean(business_og_rag),
                    'raw_llm_mean': np.mean(business_raw_llm),
                    'difference': np.mean(business_og_rag) - np.mean(business_raw_llm)
                },
                'overall_fluency': {
                    'og_rag_mean': np.mean(fluency_og_rag),
                    'raw_llm_mean': np.mean(fluency_raw_llm),
                    'difference': np.mean(fluency_og_rag) - np.mean(fluency_raw_llm)
                }
            }
        }
        
        # Perform t-tests
        try:
            # Overall score comparison
            t_stat, p_value = stats.ttest_rel(og_rag_scores, raw_llm_scores)
            statistical_results['statistical_tests'] = {
                'paired_t_test': {
                    't_statistic': t_stat,
                    'p_value': p_value,
                    'significant': p_value < 0.05
                }
            }
            
            # Effect size (Cohen's d)
            pooled_std = np.sqrt(((np.std(og_rag_scores) ** 2) + (np.std(raw_llm_scores) ** 2)) / 2)
            cohens_d = (np.mean(og_rag_scores) - np.mean(raw_llm_scores)) / pooled_std
            statistical_results['statistical_tests']['effect_size'] = cohens_d
            
        except Exception as e:
            logger.warning(f"Statistical test failed: {e}")
            
        return statistical_results
        
